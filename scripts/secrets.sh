#!/usr/bin/env bash
# Writes include/secrets.h (gitignored) from two 1Password items. Values are never printed.
#
#   EZB_OP_VAULT       vault ID holding both items
#   EZB_WIFI_ITEM      item with fields labelled wifi_network and wifi_password (home network)
#   EZB_BRIDGE_ITEM    item with fields labelled ezshare_ssid, ezshare_password, ota_password,
#                      and optionally hostname and syslog_host
#
# Set them in mise.local.toml. Signs in with the real `op` first, so you type your password
# once per run.
set -euo pipefail

: "${EZB_OP_VAULT:?set EZB_OP_VAULT in mise.local.toml}"
: "${EZB_WIFI_ITEM:?set EZB_WIFI_ITEM in mise.local.toml}"
: "${EZB_BRIDGE_ITEM:?set EZB_BRIDGE_ITEM in mise.local.toml}"

for tool in op jq; do
  command -v "$tool" >/dev/null || { echo "error: $tool not found" >&2; exit 1; }
done

if ! op whoami >/dev/null 2>&1; then
  session="$(op signin)"
  eval "$session"
fi

wifi="$(op item get "$EZB_WIFI_ITEM" --vault "$EZB_OP_VAULT" --format json)"
bridge="$(op item get "$EZB_BRIDGE_ITEM" --vault "$EZB_OP_VAULT" --format json)"

# Prints the field as a quoted C string literal. JSON string escaping is valid C for these
# values; jq exits non-zero if the field is missing.
field() {
  jq -er --arg l "$2" '[.fields[]? | select(.label == $l) | .value // empty] | first | select(. != null) | tojson' <<<"$1" \
    || { echo "error: 1Password item is missing field '$2'" >&2; exit 1; }
}

# Assignments, not inline $(...) in echo: set -e only stops on a failed assignment.
home_ssid="$(field "$wifi" wifi_network)"
home_password="$(field "$wifi" wifi_password)"
ezshare_ssid="$(field "$bridge" ezshare_ssid)"
ezshare_password="$(field "$bridge" ezshare_password)"
ota_password="$(field "$bridge" ota_password)"
hostname="$(field "$bridge" hostname 2>/dev/null)" || hostname=""
syslog_host="$(field "$bridge" syslog_host 2>/dev/null)" || syslog_host=""

out="$(cd "$(dirname "$0")/.." && pwd)/include/secrets.h"
tmp="$(mktemp "${out}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

{
  echo "// Generated by scripts/secrets.sh from 1Password. Don't commit."
  echo "#pragma once"
  echo "#define HOME_WIFI_SSID $home_ssid"
  echo "#define HOME_WIFI_PASSWORD $home_password"
  echo "#define EZSHARE_SSID $ezshare_ssid"
  echo "#define EZSHARE_PASSWORD $ezshare_password"
  echo "#define OTA_PASSWORD $ota_password"
  if [[ -n "$hostname" ]]; then
    echo "#define BRIDGE_HOSTNAME $hostname"
  fi
  if [[ -n "$syslog_host" ]]; then
    echo "#define SYSLOG_HOST $syslog_host"
  fi
} >"$tmp"
chmod 600 "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
